import { expect, test, type Page } from "@playwright/test";
import { credentials, login, assertNoOverflow } from "./helpers";

test.use({ actionTimeout: 15_000, navigationTimeout: 20_000 });

type User = {
  id: number;
  username: string;
  email: string;
  is_active: boolean;
  groups: { id: number; name: string }[];
  explicit_permissions: Record<string, boolean>;
  effective_permissions: Record<string, boolean>;
  permission_sources: Record<string, string>;
};
type Group = { id: number; name: string; members: { id: number }[] };
async function headers(page: Page) {
  const response = await page.request.get("/api/auth/csrf/");
  const body = await response.json();
  return { "X-CSRFToken": body.csrfToken, Origin: "http://127.0.0.1:8091" };
}
async function userByName(
  page: Page,
  username: string,
): Promise<User | undefined> {
  const response = await page.request.get("/api/access/users/");
  expect(response.ok()).toBeTruthy();
  return ((await response.json()).users as User[]).find(
    (user) => user.username === username,
  );
}
async function cleanup(page: Page, username: string, groupName?: string) {
  // Only entities generated by this test are eligible for cleanup.
  expect(username.startsWith("qa_gov_")).toBeTruthy();
  const authHeaders = await headers(page);
  const user = await userByName(page, username);
  if (user)
    await page.request.delete(`/api/access/users/${user.id}/`, {
      headers: authHeaders,
    });
  if (groupName) {
    expect(groupName.startsWith("qa_gov_")).toBeTruthy();
    const response = await page.request.get("/api/access/groups/");
    const group = ((await response.json()).groups as Group[]).find(
      (item) => item.name === groupName,
    );
    if (group)
      await page.request.delete(`/api/access/groups/${group.id}/`, {
        headers: authHeaders,
      });
  }
}
async function openUser(page: Page, username: string) {
  await page.goto("/governance/users");
  await page.getByPlaceholder("Найти пользователя или группу").fill(username);
  await page
    .getByRole("row")
    .filter({ hasText: username })
    .getByRole("button", { name: "Настроить", exact: true })
    .click();
  await expect(page.getByRole("dialog")).toBeVisible();
}
